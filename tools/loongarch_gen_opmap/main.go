// argToProcessor 将操作数转换为处理器表达式
func argToProcessor(mnemonic string, idx int, arg *Arg) string {
	if arg == nil {
		return "Unknown"
	}
	if len(arg.Slots) == 0 {
		return "Unknown"
	}

	insn_scaled := map[string]int{

		"ll.d": 2,
		"sc.d": 2,
		"ll.w": 2,
		"sc.w": 2,

		// "st.h": 1,
		// "st.w": 2,
		// "st.d": 3,

		// "ld.h":  1,
		// "ld.w":  2,
		// "ld.d":  3,
		// "ld.hu": 2,
		// "ld.wu": 2,

		"vldrepl.h":  1,
		"vstelm.h":   1,
		"xvldrepl.h": 1,
		"xvstelm.h":  1,

		// "pcaddi":    1,
		// "pcaddu12i": 2,
		// "pcaddu18i": 2,
		// "pcalau12i": 2,

		"ldptr.w": 2,
		"stptr.w": 2,
		"ldptr.d": 2,
		"stptr.d": 2,

		"vldrepl.w":  2,
		"vstelm.w":   2,
		"xvldrepl.w": 2,
		"xvstelm.w":  2,

		"vldrepl.d":  3,
		"vstelm.d":   3,
		"xvldrepl.d": 3,
		"xvstelm.d":  3,

		"beq":   2,
		"bne":   2,
		"blt":   2,
		"bge":   2,
		"bltu":  2,
		"bgeu":  2,
		"beqz":  2,
		"bnez":  2,
		"b":     2,
		"bl":    2,
		"jirl":  2,
		"bceqz": 2,
		"bcnez": 2,
	}

	switch arg.Kind {
	case ArgKindIntReg:
		if (mnemonic == "movfcsr2gr" || mnemonic == "movgr2fcsr") &&
			idx == 1 {
			return fmt.Sprintf("FCSR(%d)", arg.Slots[0].Offset)
		} else {
			return fmt.Sprintf("R(%d)", arg.Slots[0].Offset)
		}
	case ArgKindFPReg:
		return fmt.Sprintf("F(%d)", arg.Slots[0].Offset)
	case ArgKindVReg:
		return fmt.Sprintf("V(%d)", arg.Slots[0].Offset)
	case ArgKindXReg:
		return fmt.Sprintf("X(%d)", arg.Slots[0].Offset)
	case ArgKindFCCReg:
		return fmt.Sprintf("C(%d)", arg.Slots[0].Offset)
	case ArgKindScratchReg:
		return fmt.Sprintf("T(%d)", arg.Slots[0].Offset)
	case ArgKindSignedImm:
		scaled, ok := insn_scaled[mnemonic]
		if ok {
			return fmt.Sprintf("Sscaled(%d, %d, %d)", arg.Slots[0].Offset, arg.Slots[0].Width, scaled)
		}
		if len(arg.Slots) == 1 {
			return fmt.Sprintf("SImm(%d, %d)", arg.Slots[0].Offset, arg.Slots[0].Width)
		} else {
			var parts []string
			for _, slot := range arg.Slots {
				parts = append(parts, fmt.Sprintf("%d, %d", slot.Offset, slot.Width))
			}
			return fmt.Sprintf("Sfields(&[%s])", strings.Join(parts, ", "))
		}
	case ArgKindUnsignedImm:

		if mnemonic == "alsl.w" || mnemonic == "alsl.d" || mnemonic == "alsl.wu" {
			return fmt.Sprintf("Usubone(%d, %d)", arg.Slots[0].Offset, arg.Slots[0].Width)
		}
		if (mnemonic == "bstrins.d" || mnemonic == "bstrins.w" ||
			mnemonic == "bstrpick.d" || mnemonic == "bstrpick.w") &&
			idx == 3 {
			return fmt.Sprintf("Ulep(%d, %d)", arg.Slots[0].Offset, arg.Slots[0].Width)
		}
		if len(arg.Slots) == 1 {
			return fmt.Sprintf("UImm(%d, %d)", arg.Slots[0].Offset, arg.Slots[0].Width)
		} else {
			var parts []string
			for _, slot := range arg.Slots {
				parts = append(parts, fmt.Sprintf("%d, %d", slot.Offset, slot.Width))
			}
			return fmt.Sprintf("Ufields(&[%s])", strings.Join(parts, ", "))
		}
	case ArgKindOffsetSI20:
		// 特殊处理分支指令
		if mnemonic == "beq" || mnemonic == "bne" ||
			mnemonic == "blt" || mnemonic == "bge" ||
			mnemonic == "bltu" || mnemonic == "bgeu" ||
			mnemonic == "jirl" {
			return "Offset(B)"
		} else if mnemonic == "b" || mnemonic == "bl" {
			return "Offset(J)"
		} else if mnemonic == "beqz" || mnemonic == "bnez" ||
			mnemonic == "bceqz" || mnemonic == "bcnez" {
			return "Offset(BZ)"
		}
		return "Offset(SI20)"
	case ArgKindOffsetSI14:
		return "Offset(SI14)"
	case ArgKindOffsetSI12:
		return "Offset(SI12)"
	case ArgKindOffsetSI16:
		return "Offset(SI16)"
	default:
		return "Unknown"
	}
}
