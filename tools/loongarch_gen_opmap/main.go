type InsnDescription struct {
	Word       uint32
	Mnemonic   string
	Format     *InsnFormat
	OrigFormat *InsnFormat
	Attribs    map[string]string
}

type InsnFormat struct {
	Args []*Arg
}

type Arg struct {
	Kind  ArgKind
	Slots []*Slot
	Post  PostprocessOp
}

type Slot struct {
	Offset uint
	Width  uint
}

type PostprocessOp struct {
	Kind   PostprocessOpKind
	Amount int
}

type PostprocessOpKind int

const (
	PostprocessOpKindNone PostprocessOpKind = 0
	PostprocessOpKindAdd  PostprocessOpKind = 1
	PostprocessOpKindShl  PostprocessOpKind = 2
)

type ArgKind int

const (
	ArgKindUnknown     ArgKind = 0
	ArgKindIntReg      ArgKind = 1
	ArgKindFPReg       ArgKind = 2
	ArgKindFCCReg      ArgKind = 3
	ArgKindScratchReg  ArgKind = 4
	ArgKindVReg        ArgKind = 5
	ArgKindXReg        ArgKind = 6
	ArgKindSignedImm   ArgKind = 7
	ArgKindUnsignedImm ArgKind = 8
	ArgKindOffsetSI20  ArgKind = 9
	ArgKindRefOffset   ArgKind = 10
	ArgKindRefLabel    ArgKind = 11
	ArgKindOffsetSI14  ArgKind = 12
	ArgKindOffsetSI12  ArgKind = 13
	ArgKindOffsetSI16  ArgKind = 14
)

func main() {
	if len(os.Args) < 3 {
		fmt.Println("Usage: loongarch_gen_opmap <input-dir> <output-file>")
		os.Exit(1)
	}

	inputDir := os.Args[1]
	outputFile := os.Args[2]

	// 1. 读取并解析所有指令定义文件
	inputs, err := filepath.Glob(inputDir + "/*.txt")
	if err != nil {
		panic(err)
	}

	commonDescs, err := common.ReadInsnDescs(inputs)
	if err != nil {
		panic(err)
	}

	// 转换 common.InsnDescription 到本地 InsnDescription
	var descs []InsnDescription
	for _, d := range commonDescs {
		descs = append(descs, InsnDescription{
			Word:       d.Word,
			Mnemonic:   d.Mnemonic,
			Format:     convertFormat(d.Format),
			OrigFormat: convertFormat(d.OrigFormat),
			Attribs:    d.Attribs,
		})
	}

	// 2. 对特定指令进行特殊处理
	descs = processSpecialInstructions(descs)

	// 3. 生成opmap.rs文件
	if err := generateOpmapFile(outputFile, descs); err != nil {
		fmt.Printf("Error generating opmap.rs: %v\n", err)
		os.Exit(1)
	}
}

// generateOpmapFile 生成opmap.rs文件
func generateOpmapFile(path string, insns []InsnDescription) error {
	file, err := os.Create(path)
	if err != nil {
		return err
	}
	defer file.Close()

	// 写入文件头
	file.WriteString("// This file was generated by tools/loongarch_gen_opmap\n")
	file.WriteString("Ops!(\n\n")

	// 按助记符分组
	insnMap := make(map[string][]InsnDescription)
	for _, insn := range insns {
		insnMap[insn.Mnemonic] = append(insnMap[insn.Mnemonic], insn)
	}

	// 按助记符排序
	var mnemonics []string
	for m := range insnMap {
		mnemonics = append(mnemonics, m)
	}
	sort.Strings(mnemonics)

	// 生成每条指令的条目
	for _, mnemonic := range mnemonics {
		group := insnMap[mnemonic]
		shouldSkip := false
		// 检查是否需要显示原始名称
		showOrigName := false
		for _, insn := range group {
			if _, ok := insn.Attribs["lbt"]; ok {
				shouldSkip = true
			}
			if origName, ok := insn.Attribs["orig_name"]; ok && origName != mnemonic {
				showOrigName = true
				mnemonic = origName
			}
		}
		if shouldSkip {
			continue // 忽略LBT指令，它们在opmap中不显示
		}
		file.WriteString(fmt.Sprintf("\"%s\" = [\n", mnemonic))

		// 生成每个编码变体
		for _, insn := range group {
			if showOrigName {
				if origName, ok := insn.Attribs["orig_name"]; ok {
					file.WriteString(fmt.Sprintf("    // orig_name: %s\n", origName))
				}
			}

			// 格式化编码为0bxxxx_xxxx_xxxx_xxxx，确保32位
			bits := fmt.Sprintf("%032b", insn.Word)
			if len(bits) != 32 {
				return fmt.Errorf("invalid instruction word length: %d", len(bits))
			}
			formattedBits := fmt.Sprintf("0b%s_%s_%s_%s",
				bits[0:8], bits[8:16], bits[16:24], bits[24:32])

			var args = insn.Format.Args

			if insn.OrigFormat != nil {
				args = insn.OrigFormat.Args
			}
			// 生成操作数列表
			var argList []string
			for idx, arg := range args {
				argList = append(argList, argToRust(mnemonic, idx, arg))
			}

			// 生成处理器列表
			var procList []string

			for idx, arg := range args {
				procList = append(procList, argToProcessor(mnemonic, idx, arg))
			}

			file.WriteString(fmt.Sprintf("    %s = [%s] => [%s];\n",
				formattedBits, strings.Join(argList, ", "), strings.Join(procList, ", ")))
		}

		file.WriteString("]\n\n")
	}

	file.WriteString(")\n")
	return nil
}

// argToRust 将操作数转换为Rust宏参数
func argToRust(mnemonic string, idx int, arg *Arg) string {
	if arg == nil {
		return "Unknown"
	}

	switch arg.Kind {
	case ArgKindIntReg:
		if (mnemonic == "movfcsr2gr" || mnemonic == "movgr2fcsr") &&
			idx == 1 {
			return "FCSR"
		} else {
			return "R"
		}
	case ArgKindFPReg:
		return "F"
	case ArgKindFCCReg:
		return "C"
	case ArgKindScratchReg:
		return "T"
	case ArgKindVReg:
		return "V"
	case ArgKindXReg:
		return "X"
	case ArgKindSignedImm, ArgKindUnsignedImm:
		return "Imm"
	case ArgKindOffsetSI20, ArgKindOffsetSI12, ArgKindOffsetSI14, ArgKindOffsetSI16:
		return "Offset"

	default:
		if len(arg.Slots) == 0 {
			return "Unknown"
		}
		if len(arg.Slots) == 1 {
			return "Imm"
		}
		return "Unknown"
	}
}

// convertFormat 转换 common.InsnFormat 到本地 InsnFormat
func convertFormat(f *common.InsnFormat) *InsnFormat {
	if f == nil {
		return nil
	}
	var args []*Arg
	for _, a := range f.Args {
		args = append(args, &Arg{
			Kind:  ArgKind(a.Kind),
			Slots: convertSlots(a.Slots),
			Post:  convertPost(a.Post),
		})
	}
	return &InsnFormat{Args: args}
}

func copyFormat(f *InsnFormat) *InsnFormat {
	if f == nil {
		return nil
	}
	var args []*Arg
	for _, a := range f.Args {
		args = append(args, &Arg{
			Kind:  ArgKind(a.Kind),
			Slots: copySlots(a.Slots),
			Post:  copyPost(a.Post),
		})
	}
	return &InsnFormat{Args: args}
}

// convertSlots 转换 common.Slot 到本地 Slot
func copySlots(slots []*Slot) []*Slot {
	var result []*Slot
	for _, s := range slots {
		result = append(result, &Slot{
			Offset: s.Offset,
			Width:  s.Width,
		})
	}
	return result
}

// convertPost 转换 common.PostprocessOp 到本地 PostprocessOp
func copyPost(p PostprocessOp) PostprocessOp {
	return PostprocessOp{
		Kind:   PostprocessOpKind(p.Kind),
		Amount: p.Amount,
	}
}

// convertSlots 转换 common.Slot 到本地 Slot
func convertSlots(slots []*common.Slot) []*Slot {
	var result []*Slot
	for _, s := range slots {
		result = append(result, &Slot{
			Offset: s.Offset,
			Width:  s.Width,
		})
	}
	return result
}

// convertPost 转换 common.PostprocessOp 到本地 PostprocessOp
func convertPost(p common.PostprocessOp) PostprocessOp {
	return PostprocessOp{
		Kind:   PostprocessOpKind(p.Kind),
		Amount: p.Amount,
	}
}

